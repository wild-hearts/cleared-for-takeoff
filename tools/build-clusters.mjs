#!/usr/bin/env node
/**
 * build-clusters.mjs — make the content clusters bidirectional.
 *
 * The audience pages already link DOWN to the two or three articles that serve
 * them. Almost no article linked back UP: four of seven pointed at a single
 * audience page and three pointed at none. So a reader who arrived on an
 * article from search had no route to the page that sells to them, and the
 * clusters passed ranking signal in one direction only.
 *
 * The downward links were a curated judgement about which article suits which
 * audience, so they are the source of truth. partials/clusters.json is derived
 * from them, and this injects the matching upward link into each article.
 *
 *   node tools/build-clusters.mjs [--check]
 *
 * Idempotent, and it will not emit a link to an audience page that does not
 * exist on disk.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const cfg = JSON.parse(readFileSync(join(ROOT, 'partials/clusters.json'), 'utf8'));

const OPEN = '<!-- @cluster:serves DO NOT EDIT BELOW. Generated by tools/build-clusters.mjs from partials/clusters.json -->';
const CLOSE = '<!-- @endcluster:serves -->';
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

const decode = (s) => s.replace(/&amp;/g, '&');

function block(audiences) {
  const items = audiences
    .map((a) => `      <li><a href="${a}">${decode(cfg.audience_labels[a] || a)}</a></li>`)
    .join('\n');
  return `${OPEN}
<section class="serves" aria-labelledby="serves-h">
  <h2 id="serves-h">Who this one is for</h2>
  <p>This article comes up most for these groups. Each has its own version of the course, with the examples and prompts rewritten for that field.</p>
  <ul>
${items}
    </ul>
  <p class="more">Not sure which fits? <a href="/who-its-for/">See all eleven doors</a>, or <a href="/ai-course-for-beginners/">read what the course covers</a>.</p>
</section>
${CLOSE}`;
}

let written = 0;
const drifted = [];
const problems = [];

for (const [article, audiencesRaw] of Object.entries(cfg.article_serves)) {
  const path = article.replace(/^\//, '').replace(/\/$/, '') + '/index.html';
  const abs = join(ROOT, path);
  if (!existsSync(abs)) { problems.push(`${path}: article not found`); continue; }

  // Never link to a door that does not exist.
  const audiences = audiencesRaw.filter((a) => {
    const ok = existsSync(join(ROOT, a.replace(/^\//, '').replace(/\/$/, '') + '/index.html'));
    if (!ok) problems.push(`${path}: ${a} does not exist, dropped`);
    return ok;
  });
  if (!audiences.length) continue;

  const original = readFileSync(abs, 'utf8');
  let html = original;
  const marked = new RegExp(`\\n?${escapeRe(OPEN)}[\\s\\S]*?${escapeRe(CLOSE)}\\n?`);
  html = html.replace(marked, '\n');

  /* Placed immediately before the audience directory, so it sits after the
     article's own related-reading section and before the site chrome. */
  const anchor = html.match(/\n?<!-- @chrome:audience\b/);
  if (!anchor) { problems.push(`${path}: no audience-directory anchor, skipped`); continue; }
  html = html.slice(0, anchor.index) + '\n' + block(audiences) + html.slice(anchor.index);

  if (html !== original) {
    drifted.push(path);
    if (!CHECK) { writeFileSync(abs, html); written++; }
  }
}

for (const p of problems) console.warn('  warn  ' + p);

if (CHECK) {
  if (drifted.length) {
    console.error(`\n✗ ${drifted.length} article(s) out of sync with partials/clusters.json:`);
    for (const p of drifted) console.error('    ' + p);
    process.exit(1);
  }
  console.log(`✓ ${Object.keys(cfg.article_serves).length} articles in sync with partials/clusters.json`);
} else {
  console.log(`✓ cluster links written to ${written} of ${Object.keys(cfg.article_serves).length} articles`);
}
