#!/usr/bin/env node
/**
 * build-glossary.mjs — FT-07.
 *
 * The visible definition list and the DefinedTermSet markup on /ai-glossary/
 * were maintained separately, which is the actual defect: two hand-kept lists
 * of the same twenty terms will drift, and a count mismatch is only the first
 * symptom you notice. Both are now generated from partials/glossary.json, so
 * they cannot disagree.
 *
 * Also adds what was genuinely missing: `url` and `inDefinedTermSet` on every
 * term so each definition is separately linkable and citable, and a jump-list
 * at the top of the page.
 *
 *   node tools/build-glossary.mjs [--check]
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const PAGE = 'ai-glossary/index.html';
const URL = 'https://www.clearedfortakeoff.com.au/ai-glossary/';
const SET_ID = `${URL}#set`;

const terms = JSON.parse(readFileSync(join(ROOT, 'partials/glossary.json'), 'utf8'));

const slugs = new Set();
for (const t of terms) {
  if (!t.slug || !t.name || !t.definition) throw new Error(`glossary.json: incomplete entry ${JSON.stringify(t)}`);
  if (slugs.has(t.slug)) throw new Error(`glossary.json: duplicate slug "${t.slug}"`);
  slugs.add(t.slug);
}

const OPEN = (n) => `<!-- @glossary:${n} DO NOT EDIT BELOW. Generated by tools/build-glossary.mjs from partials/glossary.json -->`;
const CLOSE = (n) => `<!-- @endglossary:${n} -->`;
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/* ---- the visible list ---- */
const list = terms
  .map((t) => `      <div class="term" id="${t.slug}">\n        <dt>${t.name}</dt>\n        <dd>${t.definition}</dd>\n      </div>`)
  .join('\n');

/* ---- the jump list ---- */
const jump =
  `    <nav class="term-jump" aria-label="Jump to a term">\n` +
  terms.map((t) => `      <a href="#${t.slug}">${t.name}</a>`).join('\n') +
  `\n    </nav>`;

/* ---- the markup's twin ---- */
const schema = JSON.stringify(
  {
    '@context': 'https://schema.org',
    '@type': 'DefinedTermSet',
    '@id': SET_ID,
    name: 'AI terms in plain English',
    description: 'A plain-English glossary of common AI terms, for everyday adults.',
    url: URL,
    inLanguage: 'en-AU',
    publisher: { '@id': 'https://www.clearedfortakeoff.com.au/#org' },
    hasDefinedTerm: terms.map((t) => ({
      '@type': 'DefinedTerm',
      '@id': `${URL}#${t.slug}`,
      name: t.name,
      description: t.definition,
      url: `${URL}#${t.slug}`,
      inDefinedTermSet: { '@id': SET_ID },
    })),
  },
  null,
  2
);

const region = (html, name, body, fallback) => {
  const marked = new RegExp(`${escapeRe(OPEN(name))}[\\s\\S]*?${escapeRe(CLOSE(name))}`);
  const block = `${OPEN(name)}\n${body}\n${CLOSE(name)}`;
  if (marked.test(html)) return html.replace(marked, block);
  if (fallback && fallback.test(html)) return html.replace(fallback, block);
  return null;
};

const original = readFileSync(join(ROOT, PAGE), 'utf8');
let html = original;

/* Marker text has changed once. Normalise any earlier form to the current one
   so a rename does not orphan the regions and duplicate the whole glossary. */
html = html.replace(/<!-- @glossary:(\w+)[^>]*-->/g, (m, name) => (m.includes('@endglossary') ? m : OPEN(name)));

/* 1. the definition list */
const withList = region(html, 'list', list, /<div class="term" id="[\s\S]*?<\/dd>\s*<\/div>(?![\s\S]*<div class="term")/);
if (withList === null) throw new Error('could not locate the glossary term list');
html = withList;

/* 2. the jump list, immediately before the <dl> */
const withJump = region(html, 'jump', jump, /(?=\s*<dl)/);
if (withJump === null) throw new Error('could not locate the <dl> to place the jump list before');
html = withJump;

/* 3. the schema twin, replacing the hand-kept DefinedTermSet block */
const schemaBlock = `<script type="application/ld+json" id="glossary-terms">\n${schema}\n</script>`;
const existing = new RegExp(`${escapeRe(OPEN('schema'))}[\\s\\S]*?${escapeRe(CLOSE('schema'))}`);
if (existing.test(html)) {
  html = html.replace(existing, `${OPEN('schema')}\n${schemaBlock}\n${CLOSE('schema')}`);
} else {
  const old = /<script type="application\/ld\+json">\s*\{[^<]*"DefinedTermSet"[\s\S]*?<\/script>/;
  if (!old.test(html)) throw new Error('could not locate the DefinedTermSet block');
  html = html.replace(old, `${OPEN('schema')}\n${schemaBlock}\n${CLOSE('schema')}`);
}

if (html === original) {
  console.log(`✓ ${PAGE} already in sync (${terms.length} terms)`);
  process.exit(0);
}
if (CHECK) {
  console.error(`✗ ${PAGE} is out of sync with partials/glossary.json`);
  process.exit(1);
}
writeFileSync(join(ROOT, PAGE), html);
console.log(`✓ ${PAGE} rebuilt from partials/glossary.json (${terms.length} terms, list + jump-list + schema)`);
